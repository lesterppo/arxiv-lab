"""Anytime evaluation of when coding agents should stop (arXiv:2611.22901,
Yang, Xue, Dong, Zhang, Zheng, Wang).

Paper claim implemented: coding agents keep working after their own tests
pass, and the value of that continued work varies widely. Anytime
evaluation replays recorded runs, scores intermediate patches with hidden
tests, and measures the cost at each step, so stopping policies can be
compared on the SAME trajectories (paired comparisons, no new rollouts).
The paper's headline results on ~6,000 SWE-bench Verified runs of eight
open models in two scaffolds: the hindsight saving available at passing
self-tests ranges from under 1% to 57%; a rule that stops after the SAME
patch passes self-tests twice saves 23% in a preregistered replication,
but the preregistered quality test does not establish non-inferiority;
fine-tuning agents to imitate the rule saves 30%.

This module implements the anytime-evaluation harness (trajectory model +
stopping policies + paired metrics). The paper's 6,000 recorded
trajectories are not public, so trajectories here are generated by a
CALIBRATED synthetic model (see TrajectoryParams): every parameter is
documented with the paper aggregate it is calibrated to, or marked as an
explicit assumption. The verdict ceiling is therefore SUPPORTED, never
VERIFIED -- see the session README.

Two modelling choices matter and are deliberate:
- Self-test outcomes are STICKY per patch version: re-running the same
  tests on an unchanged patch returns the same result (deterministic
  tests). A fresh self-test draw happens only when the patch changes.
  Without this, a per-step false-pass rate compounds over 30 steps and
  the first self-pass lands absurdly early.
- The agent's change decision depends on the SELF-test outcome it can
  see (it edits after a self-fail, mostly re-runs tests after a
  self-pass), never on the hidden state it cannot see.

Stdlib only. No model calls, no network at import time. Deterministic:
all randomness flows through SplitMix64, implemented identically in the
Rust second stage so Python-vs-Rust parity is bit-exact.
"""

