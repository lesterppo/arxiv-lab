_MASK64 = (1 << 64) - 1
_GOLDEN = 0x9E3779B97F4A7C15


class SplitMix64:
    """SplitMix64 PRNG (Stafford). Identical arithmetic in the Rust port.

    ``uniform()`` returns a float in [0, 1) with 53 bits of randomness:
    ``(next_u64() >> 11) * 2**-53``. Seeded identically, Python and Rust
    produce the same stream bit-for-bit.
    """

    def __init__(self, seed):
        self.state = int(seed) & _MASK64

    def next_u64(self):
        self.state = (self.state + _GOLDEN) & _MASK64
        z = self.state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & _MASK64
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & _MASK64
        return z ^ (z >> 31)

    def uniform(self):
        return (self.next_u64() >> 11) * (1.0 / 9007199254740992.0)

    def bernoulli(self, p):
        return self.uniform() < p


class TrajectoryParams:
    """Parameters of the calibrated synthetic trajectory model.

    Each field documents its calibration source. Fields marked
    [paper] come from an aggregate reported in the abstract; fields
    marked [assumption] are explicit modelling choices, not paper
    numbers -- changing them is a sensitivity check, not a refutation.

    A run is a sequence of steps (``budget`` at most). At each step the
    agent emits a patch (``patch_id`` increments when the patch
    changes); the patch has a hidden-test state (``hidden_pass``) and
    a self-test state (``self_pass``, a noisy proxy of the hidden
    state, sticky per patch version). Trajectories are generated once,
    policy-independently -- exactly the paper's replay setup -- so
    policies are compared on the same runs.
    """

    def __init__(
        self,
        budget=30,
        p_solvable=0.65,
        p_fix=0.03,
        p_change_after_self_pass=0.15,
        p_change_after_self_fail=0.90,
        p_break=0.08,
        p_self_false_pass=0.01,
        p_self_false_fail=0.15,
    ):
        self.budget = int(budget)
        self.p_solvable = float(p_solvable)
        self.p_fix = float(p_fix)
        self.p_change_after_self_pass = float(p_change_after_self_pass)
        self.p_change_after_self_fail = float(p_change_after_self_fail)
        self.p_break = float(p_break)
        self.p_self_false_pass = float(p_self_false_pass)
        self.p_self_false_fail = float(p_self_false_fail)

    def to_dict(self):
        return {
            "budget": self.budget,
            "p_solvable": self.p_solvable,
            "p_fix": self.p_fix,
            "p_change_after_self_pass": self.p_change_after_self_pass,
            "p_change_after_self_fail": self.p_change_after_self_fail,
            "p_break": self.p_break,
            "p_self_false_pass": self.p_self_false_pass,
            "p_self_false_fail": self.p_self_false_fail,
        }

    @classmethod
    def from_dict(cls, d):
        return cls(**d)

    def with_overrides(self, **kw):
        d = self.to_dict()
        d.update(kw)
        return TrajectoryParams.from_dict(d)


# Calibrated regime. Sources:
# - budget=30 [assumption]: a typical SWE-agent step budget; the paper
#   reports cost per step, and 30 is the common cap in the scaffolds it
#   studies. Saving percentages are budget-relative, so the headline
#   numbers move slowly with this choice (see sensitivity in the test).
# - p_solvable=0.65 [paper]: the eventual hidden-pass rate of the
#   calibrated model lands at ~0.31, inside the 0.30-0.50 resolve-rate
#   band of open models on SWE-bench Verified that the paper's eight
#   models sit in.
# - p_fix=0.03 [assumption]: per-change repair hazard for a failing
#   patch on a solvable run; together with p_change_after_self_fail
#   it sets the first-pass step distribution (mean first hidden pass
#   ~step 15) and hence the hindsight/oracle savings.
# - p_change_after_self_pass=0.15 [paper]: the paper's central
#   observation is that agents keep working after their tests pass,
#   but "working" is mostly re-running tests and verifying, not
#   editing: after a self-pass the agent edits the patch only 15% of
#   steps, which is what lets the double-pass rule fire ~1 step after
#   the first self-pass while still saving only ~26% (the first
#   self-pass itself lands late, ~step 19).
# - p_change_after_self_fail=0.90 [assumption]: while its own tests
#   fail, the agent almost always edits rather than re-running them.
# - p_break=0.08 [paper]: the paper explains cross-model differences
#   by how often post-pass changes repair vs break the patch; 0.08 is
#   the break share that keeps the double-pass rule's quality delta
#   near zero (+1.4pp in the calibrated regime; repairs and breaks
#   roughly balance), matching the paper's "quality preservation
#   remains uncertain". The sensitivity sweep varies this 0.05-0.30
#   and the delta changes sign.
# - p_self_false_pass=0.01 [assumption]: a patch that fails hidden
#   tests usually fails the agent's own tests too; a 1% false-pass
#   rate per new patch is what lets the first-pass rule stop on broken
#   patches (the quality risk the paper warns about) without the
#   false passes compounding over 30 steps. (An earlier v1 model with
#   a per-step 15% false-pass rate put 60% of first self-passes on
#   broken patches and the hindsight saving at 86% -- both outside
#   the paper's ranges; the sticky-per-patch + 1% calibration fixed
#   both.)
# - p_self_false_fail=0.15 [assumption]: self-tests miss 15% of true
#   passes, so a good patch is sometimes discarded -- the agent
#   "fixes" something that is not broken.
CALIBRATED = TrajectoryParams()


class Step:
    """One step of a recorded run: the patch emitted and its test states."""

    __slots__ = ("step", "patch_id", "changed", "hidden_pass", "self_pass")

    def __init__(self, step, patch_id, changed, hidden_pass, self_pass):
        self.step = int(step)
        self.patch_id = int(patch_id)
        self.changed = bool(changed)
        self.hidden_pass = bool(hidden_pass)
        self.self_pass = bool(self_pass)

    def to_list(self):
        return [self.step, self.patch_id, self.changed,
                self.hidden_pass, self.self_pass]

    def __repr__(self):  # pragma: no cover - debugging aid
        return ("Step(step=%d, patch=%d, changed=%s, hidden=%s, self=%s)"
                % (self.step, self.patch_id, self.changed,
                   self.hidden_pass, self.self_pass))


def generate_trajectory(rng, params=None):
    """Generate one run (list of Step) under ``params``.

    Draw order per step (fixed -- the Rust port mirrors it exactly):
    solvable flag once, then per step: change?, hidden update (only on
    a change, and only the draw the branch needs), self-test outcome
    (only on a change; unchanged patches keep their sticky result).
    A policy never influences the trajectory: stopping only selects a
    prefix, as in the paper's replay of recorded runs.
    """
    params = params or CALIBRATED
    solvable = rng.bernoulli(params.p_solvable)
    steps = []
    hidden = False
    patch_id = 0
    prev_self = False
    for t in range(1, params.budget + 1):
        if t == 1:
            changed = True
        else:
            p_change = (params.p_change_after_self_pass if prev_self
                        else params.p_change_after_self_fail)
            changed = rng.bernoulli(p_change)
        if changed:
            patch_id += 1
            if hidden:
                # A change to a passing patch breaks it with p_break.
                if rng.bernoulli(params.p_break):
                    hidden = False
            elif solvable:
                # A change to a failing patch repairs it with p_fix.
                if rng.bernoulli(params.p_fix):
                    hidden = True
            if hidden:
                self_pass = not rng.bernoulli(params.p_self_false_fail)
            else:
                self_pass = rng.bernoulli(params.p_self_false_pass)
        else:
            # Same patch, same tests: the sticky self-test result.
            self_pass = prev_self
        steps.append(Step(t, patch_id, changed, hidden, self_pass))
        prev_self = self_pass
    return steps


def stop_run_to_budget(traj):
    """(a) Baseline: run to the step budget."""
    return len(traj)


def stop_first_self_pass(traj):
    """(b) Stop at the first self-test pass."""
    for s in traj:
        if s.self_pass:
            return s.step
    return len(traj)


def stop_double_pass(traj):
    """(c) The paper's rule: stop after the SAME patch passes self-tests
    twice in a row. The consecutive-pass counter resets when the patch
    changes or a self-test fails -- two consecutive passes of an
    unchanged patch are the evidence the rule requires."""
    count = 0
    current_patch = None
    for s in traj:
        if s.patch_id != current_patch:
            current_patch = s.patch_id
            count = 0
        if s.self_pass:
            count += 1
            if count >= 2:
                return s.step
        else:
            count = 0
    return len(traj)


def stop_double_pass_cumulative(traj):
    """Sensitivity variant of (c): the same patch passes twice
    cumulatively (a self-test failure does not reset the count, only a
    patch change does). NOTE: under sticky self-tests this coincides
    with the consecutive rule exactly -- within one patch version the
    self-test outcome never changes, so a self-fail can never
    intervene between two passes of the same patch. The test asserts
    the two rules return identical stop steps on every trajectory;
    keep this function as that model-consistency check, not as a
    distinct policy."""
    count = 0
    current_patch = None
    for s in traj:
        if s.patch_id != current_patch:
            current_patch = s.patch_id
            count = 0
        if s.self_pass:
            count += 1
            if count >= 2:
                return s.step
    return len(traj)


def stop_oracle(traj):
    """(d) Hindsight oracle: stop at the first step where hidden tests
    pass. Pass is maximal, so the patch never improves afterwards by
    construction; if the run never passes, run to budget."""
    for s in traj:
        if s.hidden_pass:
            return s.step
    return len(traj)


POLICIES = {
    "baseline": stop_run_to_budget,
    "first_self_pass": stop_first_self_pass,
    "double_pass": stop_double_pass,
    "double_pass_cumulative": stop_double_pass_cumulative,
    "oracle": stop_oracle,
}


def evaluate_policy(traj, stop_fn):
    """Apply a stopping policy to one trajectory.

    Returns (stop_step, cost_steps, final_hidden_pass). Cost is steps
    used; the paper measures cost incurred at each step, and one step
    is one cost unit here.
    """
    stop = stop_fn(traj)
    return stop, stop, traj[stop - 1].hidden_pass


def trajectory_digest(traj):
    """Integer summary of a trajectory for parity checks: (steps,
    hidden-pass count, self-pass count, final patch id, change count,
    first hidden-pass step or 0)."""
    hidden_passes = sum(1 for s in traj if s.hidden_pass)
    self_passes = sum(1 for s in traj if s.self_pass)
    changes = sum(1 for s in traj if s.changed)
    first_hidden = 0
    for s in traj:
        if s.hidden_pass:
            first_hidden = s.step
            break
    return [len(traj), hidden_passes, self_passes,
            traj[-1].patch_id if traj else 0, changes, first_hidden]


def paired_quality_delta(final_a, final_b):
    """Paired quality delta of policy A vs policy B over the same runs.

    ``final_a``/``final_b`` are parallel lists of bools (final hidden
    pass). Returns (delta, wins, losses, ties, (lo, hi)) where wins
    counts runs A passes and B fails, losses the reverse, and (lo, hi)
    is a normal-approximation 95% CI on the paired mean difference.
    """
    n = len(final_a)
    diffs = [ (1 if a else 0) - (1 if b else 0)
              for a, b in zip(final_a, final_b) ]
    wins = sum(1 for d in diffs if d > 0)
    losses = sum(1 for d in diffs if d < 0)
    ties = n - wins - losses
    delta = sum(diffs) / float(n)
    mean_sq = sum(d * d for d in diffs) / float(n)
    var = max(mean_sq - delta * delta, 0.0)
    se = math.sqrt(var / n)
    return delta, wins, losses, ties, (delta - 1.96 * se, delta + 1.96 * se)


def evaluate_all(trajs, params=None):
    """Evaluate every policy on the same trajectories (paired).

    Returns a dict with per-policy aggregates plus the post-fire
    analysis for the double-pass rule and the hindsight numbers.
    """
    params = params or CALIBRATED
    budget = params.budget
    out = {"n_runs": len(trajs), "budget": budget, "policies": {}}
    finals = {}
    stops = {}
    for name, fn in POLICIES.items():
        rows = [evaluate_policy(t, fn) for t in trajs]
        stops[name] = [r[0] for r in rows]
        finals[name] = [r[2] for r in rows]
        mean_cost = sum(r[1] for r in rows) / float(len(rows))
        out["policies"][name] = {
            "mean_steps": mean_cost,
            "saving_pct": 100.0 * (budget - mean_cost) / budget,
            "final_hidden_pass_rate": sum(finals[name]) / float(len(rows)),
            "fire_rate": sum(1 for s in stops[name] if s < budget)
                         / float(len(rows)),
        }
    # Post-fire analysis for the paper's rule: what would have happened
    # had the agent kept working after the rule fired?
    fired = []
    for traj, stop in zip(trajs, stops["double_pass"]):
        if stop < budget:
            fired.append((traj, stop))
    changed_after = 0
    repairs = 0
    breaks = 0
    for traj, stop in fired:
        fire_hidden = traj[stop - 1].hidden_pass
        final_hidden = traj[-1].hidden_pass
        if any(s.changed for s in traj[stop:]):
            changed_after += 1
        if not fire_hidden and final_hidden:
            repairs += 1
        if fire_hidden and not final_hidden:
            breaks += 1
    out["double_pass_post_fire"] = {
        "n_fired": len(fired),
        "changed_after_fire": changed_after,
        "changed_after_fire_rate":
            changed_after / float(len(fired)) if fired else 0.0,
        "repairs_after_fire": repairs,
        "breaks_after_fire": breaks,
    }
    # Hindsight saving available at passing self-tests (paper's
    # <1%-57% figure), two readings:
    # (A) conditional: among runs whose FIRST self-test pass is on a
    #     patch that truly passes hidden tests, the saving from
    #     stopping there.
    # (B) all-runs (primary): the saving from stopping at the first
    #     self-test pass when that patch truly passes, and 0 when it
    #     does not -- i.e. the saving hindsight says was available
    #     without losing quality. (A) is a diagnostic; (B) is the
    #     number compared against the paper's range.
    hindsight = []
    hindsight_all = []
    for traj in trajs:
        for s in traj:
            if s.self_pass:
                if s.hidden_pass:
                    hindsight.append(100.0 * (budget - s.step) / budget)
                    hindsight_all.append(100.0 * (budget - s.step)
                                         / budget)
                else:
                    hindsight_all.append(0.0)
                break
        else:
            hindsight_all.append(0.0)
    out["hindsight_at_first_self_pass"] = {
        "n_true_first_pass": len(hindsight),
        "mean_saving_pct": (sum(hindsight) / len(hindsight)
                            if hindsight else 0.0),
        "mean_saving_pct_all_runs":
            sum(hindsight_all) / float(len(hindsight_all)),
    }
    # Paired quality delta: double-pass rule vs run-to-budget baseline.
    delta, wins, losses, ties, ci = paired_quality_delta(
        finals["double_pass"], finals["baseline"])
    out["quality_delta_double_pass_vs_baseline"] = {
        "delta_pp": 100.0 * delta,
        "wins": wins,
        "losses": losses,
        "ties": ties,
        "ci_95_pp": (100.0 * ci[0], 100.0 * ci[1]),
    }
    return out


def sensitivity_sweep(params=None, n_runs=2000, seeds=(20261118, 7)):
    """Vary the regime parameters the paper says drive the value of
    continued work -- p_break (how often a post-pass change breaks the
    patch), p_change_after_self_pass (how often the agent edits after
    its tests pass), and p_self_false_pass (how often self-tests pass
    a broken patch, i.e. self-test fidelity) -- and report the
    double-pass rule's saving and paired quality delta in each cell.
    The paper's finding is that the value of continued work varies by
    model/scaffold; the sweep checks whether the sign of the quality
    delta does too.
    """
    params = params or CALIBRATED

    def cell(cell_params):
        trajs = []
        for seed in seeds:
            rng = SplitMix64(seed)
            trajs.extend(generate_trajectory(rng, cell_params)
                         for _ in range(n_runs))
        agg = evaluate_all(trajs, cell_params)
        return {
            "p_break": cell_params.p_break,
            "p_change_after_self_pass":
                cell_params.p_change_after_self_pass,
            "p_self_false_pass": cell_params.p_self_false_pass,
            "p_fix": cell_params.p_fix,
            "double_pass_saving_pct":
                agg["policies"]["double_pass"]["saving_pct"],
            "quality_delta_pp":
                agg["quality_delta_double_pass_vs_baseline"]["delta_pp"],
            "baseline_pass_rate":
                agg["policies"]["baseline"]["final_hidden_pass_rate"],
            "double_pass_pass_rate":
                agg["policies"]["double_pass"]["final_hidden_pass_rate"],
        }

    cells = []
    for p_break in (0.05, 0.12, 0.30):
        for p_change in (0.10, 0.25, 0.45):
            cells.append(cell(params.with_overrides(
                p_break=p_break, p_change_after_self_pass=p_change)))
    # Self-test fidelity axis at the calibrated break/edit rates: a
    # noisier self-test proxy fires the rule on broken patches, which
    # is where the quality losses come from.
    for fpp in (0.03, 0.05):
        cells.append(cell(params.with_overrides(p_self_false_pass=fpp)))
    return cells


def run_experiment(params=None, n_runs=2000, seeds=(20261118, 7, 123, 2026, 99)):
    """Run the experiment over ``len(seeds)`` seeds x ``n_runs`` runs.

    Each seed drives an independent SplitMix64 stream; results are
    pooled across seeds. Returns the aggregate dict from
    ``evaluate_all`` plus the seed list and per-seed double-pass
    savings (seed stability check).
    """
    params = params or CALIBRATED
    trajs = []
    per_seed = []
    for seed in seeds:
        rng = SplitMix64(seed)
        seed_trajs = [generate_trajectory(rng, params)
                      for _ in range(n_runs)]
        agg = evaluate_all(seed_trajs, params)
        per_seed.append({
            "seed": seed,
            "double_pass_saving_pct":
                agg["policies"]["double_pass"]["saving_pct"],
            "oracle_saving_pct": agg["policies"]["oracle"]["saving_pct"],
            "baseline_pass_rate":
                agg["policies"]["baseline"]["final_hidden_pass_rate"],
            "double_pass_pass_rate":
                agg["policies"]["double_pass"]["final_hidden_pass_rate"],
        })
        trajs.extend(seed_trajs)
    out = evaluate_all(trajs, params)
    out["params"] = params.to_dict()
    out["seeds"] = list(seeds)
    out["n_runs_per_seed"] = n_runs
    out["per_seed"] = per_seed
    return out


