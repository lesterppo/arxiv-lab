def main():
    global LUA_BIN
    t_start = time.time()
    install()
    LUA_BIN = setup_lua()
    if LUA_BIN is None:
        RESULTS["outcome"] = "BLOCKED"
        RESULTS["block_reason"] = ("no Lua 5.1 interpreter available "
                                   "(apt install failed); the executable "
                                   "oracle is the method -- no fair test.")
        flush_results()
        log("FRONTIER_BLOCKED: no lua interpreter")
        sys.exit(2)

    log("building fresh exam (examiner; never shown to the learner)")
    if os.path.exists(EXAM_JSON):
        exam = json.load(open(EXAM_JSON))
        log(f"exam loaded from resume file: {len(exam)} items")
    else:
        exam = exam_items()
        log(f"exam built: {len(exam)} items")
        with open(EXAM_JSON, "w") as f:
            json.dump(exam, f, indent=1)
    RESULTS["phases"].append({"phase": "exam", "n": len(exam)})

    # Resume state: a prior attempt's pool / exam / results, uploaded to
    # /content by the launcher. Skips completed proposal phases and the
    # base eval; per-item rows reload from the eval CSV for sign tests.
    prior = None
    if os.path.exists(RESULTS_JSON):
        try:
            prior = json.load(open(RESULTS_JSON))
            RESULTS["rounds"] = prior.get("rounds", {})
            RESULTS["phases"] = prior.get("phases", []) + RESULTS["phases"]
            RESULTS["sign_tests"] = prior.get("sign_tests", {})
            RESULTS["resumed_from"] = {
                "pool_records": prior.get("rounds", {}).get("round1", {}).get(
                    "pool_cumulative"),
                "base": prior.get("rounds", {}).get("base")}
            log(f"resumed from prior results: {RESULTS['resumed_from']}")
        except Exception as e:
            log(f"prior results unreadable, starting fresh: {e}")
            prior = None
    pool = []
    if os.path.exists(POOL_JSONL):
        with open(POOL_JSONL) as f:
            pool = [json.loads(ln) for ln in f if ln.strip()]
        log(f"resumed pool: {len(pool)} records")
    flush_results()

    tok = model = None
    for mid in MODELS_TRY:
        try:
            tok, model = build_model(mid)
            RESULTS["model_used"] = mid
            RESULTS["fallback_used"] = (mid != MODELS_TRY[0])
            break
        except Exception as e:
            log(f"model {mid} FAILED to load: {type(e).__name__}: {e}")
            RESULTS["phases"].append({"phase": "model_try", "model": mid,
                                      "ok": False, "error": str(e)[:300]})
            flush_results()
            gc.collect()
            try:
                import torch
                torch.cuda.empty_cache()
            except Exception:
                pass
    if model is None:
        RESULTS["outcome"] = "BLOCKED"
        RESULTS["block_reason"] = ("neither Qwen3.5-9B (transformers pin) "
                                   "nor Qwen3-8B loaded on this T4; no "
                                   "further automatic fallback exists "
                                   "(8B is the smallest proven 8-9B model).")
        flush_results()
        log("FRONTIER_BLOCKED: no model loaded")
        sys.exit(2)
    RESULTS["phases"].append({"phase": "model_load", "model": RESULTS["model_used"]})
    flush_results()

    seen_programs = {norm_program(r["program"]) for r in pool}
    seen_programs |= {norm_program(it["program"]) for it in exam}
    exam_rows = {}     # model tag -> rows (for sign tests)
    if os.path.exists(EVAL_ROWS_CSV):
        with open(EVAL_ROWS_CSV, newline="") as f:
            for row in csv.DictReader(f):
                row["correct"] = row["correct"] if row["correct"] == "" else int(row["correct"])
                row["excluded"] = int(row["excluded"])
                exam_rows.setdefault(row["model"], []).append(row)
        log(f"reloaded eval rows for: {sorted(exam_rows)}")

    # Base eval first (reference point) -- skipped on resume when the
    # base rows are already on disk.
    if "base" in exam_rows and RESULTS["rounds"].get("base"):
        log("base eval present from resume; skipping")
    else:
        correct, n_graded, n_excl, rows = eval_exam(
            tok, model, exam, None, "base", [])
        exam_rows["base"] = rows
        record_metric("base", "fresh_exam", n_graded, correct,
                      f"model={RESULTS['model_used']}")
        RESULTS["rounds"]["base"] = {"correct": correct, "n": n_graded,
                                     "excluded": n_excl}
        flush_results()

    champion = None    # adapter name of the current champion (None = base)
    for rnd, (target, budget) in enumerate(
            [(ROUND1_TARGET, PROPOSE_BUDGET_R1),
             (ROUND2_NEW, PROPOSE_BUDGET_R2)], start=1):
        tag = f"round{rnd}"
        have = sum(1 for r in pool if r.get("round") == rnd)
        if have >= target:
            log(f"== {tag}: {have}/{target} frontier programs already in "
                f"resumed pool; skipping proposals ==")
            new_frontier, n_prop, n_valid, n_f = [], 0, 0, have
        else:
            log(f"== {tag}: propose until {target} new frontier programs "
                f"(have {have}, champion={champion or 'base'}) ==")
            new_frontier, n_prop, n_valid, n_f = propose_and_select(
                tok, model, champion, target - have, budget, MANUAL_SECTIONS,
                seen_programs, tag)
            for rec in new_frontier:
                rec["round"] = rnd
                pool.append(rec)
            with open(POOL_JSONL, "w") as f:
                for rec in pool:
                    f.write(json.dumps(rec) + "\n")
        RESULTS["rounds"][tag] = {
            "new_frontier": len([r for r in pool if r.get("round") == rnd]),
            "proposed": n_prop, "valid": n_valid,
            "pool_cumulative": len(pool)}
        log(f"{tag}: frontier {len([r for r in pool if r.get('round') == rnd])} "
            f"(target {target}), pool now {len(pool)}")
        flush_results()

        if not pool:
            RESULTS["outcome"] = "BLOCKED"
            RESULTS["block_reason"] = (f"{tag}: empty frontier pool -- "
                                       "no training data collected.")
            flush_results()
            log("FRONTIER_BLOCKED: empty pool")
            sys.exit(2)

        train_rows = [train_text(r["program"], r["reference"]) for r in pool]
        steps = train_adapter(tok, model, f"gen{rnd}", train_rows, tag)
        RESULTS["rounds"][tag]["train_steps"] = steps
        flush_results()

        correct, n_graded, n_excl, rows = eval_exam(
            tok, model, exam, f"gen{rnd}", f"gen{rnd}",
            [r["program"] for r in pool])
        exam_rows[f"gen{rnd}"] = rows
        record_metric(f"gen{rnd}", "fresh_exam", n_graded, correct,
                      f"pool={len(pool)}")
        RESULTS["rounds"][tag].update({"correct": correct, "n": n_graded,
                                       "excluded": n_excl})
        flush_results()
        champion = f"gen{rnd}"

    # Sign tests per step (paper's registered rule: exact one-sided
    # binomial over discordant items, step holds at p<0.05).
    def paired(a_tag, b_tag):
        wins = losses = 0
        ra = {r["item"]: r for r in exam_rows[a_tag]}
        rb = {r["item"]: r for r in exam_rows[b_tag]}
        for item, x in ra.items():
            y = rb.get(item)
            if y is None or x["excluded"] or y["excluded"]:
                continue
            if x["correct"] == "" or y["correct"] == "":
                continue
            if int(y["correct"]) == 1 and int(x["correct"]) == 0:
                wins += 1
            elif int(y["correct"]) == 0 and int(x["correct"]) == 1:
                losses += 1
        return wins, losses, sign_test_p(wins, losses)

    for a_tag, b_tag, label in [("base", "gen1", "gen1_vs_base"),
                                ("gen1", "gen2", "gen2_vs_gen1")]:
        w, l, p = paired(a_tag, b_tag)
        RESULTS["sign_tests"][label] = {"wins": w, "losses": l, "p": p,
                                        "holds": bool(p < 0.05 and w > l)}
        log(f"sign test {label}: wins {w} losses {l} p={p:.2g} "
            f"holds={p < 0.05 and w > l}")

    # Per-template accuracy table for the report.
    tmpl = {}
    for it in exam:
        tmpl.setdefault(it["template"], {})
    for tag, rows in exam_rows.items():
        for r in rows:
            if r["excluded"]:
                continue
            d = tmpl[r["template"]].setdefault(tag, [0, 0])
            d[0] += int(r["correct"])
            d[1] += 1
    RESULTS["per_template"] = {
        t: {tag: f"{c}/{n}" for tag, (c, n) in v.items()}
        for t, v in tmpl.items()}
    RESULTS["outcome"] = "DONE"
    RESULTS["elapsed_s"] = round(time.time() - t_start)
    flush_results()
    log(f"ALL PHASES DONE in {time.time()-t_start:.0f}s")
    print("TRAIN_DONE", flush=True)


if __name__ == "__main__":
    main()
