def build_model(model_id):
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
    from peft import LoraConfig, get_peft_model
    bnb = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type="nf4",
                             bnb_4bit_use_double_quant=True,
                             bnb_4bit_compute_dtype=torch.bfloat16)
    tok = AutoTokenizer.from_pretrained(model_id)
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    tok.padding_side = "left"
    model = AutoModelForCausalLM.from_pretrained(
        model_id, quantization_config=bnb, torch_dtype=torch.bfloat16,
        device_map="auto", attn_implementation="sdpa")
    model.config.use_cache = True
    # Wrap once so add_adapter / set_adapter / disable_adapter exist for
    # every phase (base behaviour = adapter disabled).
    dummy = LoraConfig(r=8, lora_alpha=16, lora_dropout=0.0, bias="none",
                       task_type="CAUSAL_LM", target_modules=TARGET_MODULES)
    model = get_peft_model(model, dummy, adapter_name="__base__")
    model.disable_adapter()
    model.gradient_checkpointing_enable()
    model.eval()
    log(f"loaded {model_id}: "
        f"{torch.cuda.memory_allocated()/2**30:.2f} GiB allocated, "
        f"{torch.cuda.max_memory_allocated()/2**30:.2f} GiB peak")
    return tok, model


def batch_generate(tok, model, prompts, do_sample, temperature=1.0,
                   max_new_tokens=128):
    """Batched generation; returns list of decoded continuations."""
    import torch
    out_texts = []
    t0 = time.time()
    n_tokens = 0
    for i in range(0, len(prompts), GEN_BS):
        batch = prompts[i:i + GEN_BS]
        enc = tok(batch, return_tensors="pt", padding=True).to("cuda")
        with torch.no_grad():
            gen = model.generate(
                **enc, do_sample=do_sample,
                temperature=temperature if do_sample else None,
                top_p=1.0 if do_sample else None,
                max_new_tokens=max_new_tokens,
                pad_token_id=tok.pad_token_id,
                eos_token_id=tok.eos_token_id)
        n_tokens += int((gen[:, enc["input_ids"].shape[1]:] != tok.pad_token_id).sum())
        for j, g in enumerate(gen):
            cont = g[enc["input_ids"].shape[1]:]
            out_texts.append(tok.decode(cont, skip_special_tokens=True))
        if (i // GEN_BS) % 10 == 0:
            log(f"  generate {min(i + GEN_BS, len(prompts))}/{len(prompts)}")
    dt = time.time() - t0
    log(f"  generated {len(prompts)} prompts, ~{n_tokens} tokens in {dt:.0f}s "
        f"({n_tokens/max(dt, 1):.0f} tok/s)")
    return out_texts


def encode_train_example(tok, prompt, completion):
    """Tokenize prompt+completion; labels mask the prompt (completion-only)."""
    p_ids = tok(prompt, add_special_tokens=True)["input_ids"]
    c_ids = tok(completion, add_special_tokens=False)["input_ids"]
    ids = (p_ids + c_ids)[:MAX_LEN]
    labels = ([-100] * len(p_ids) + c_ids)[:MAX_LEN]
    return ids, labels


def train_adapter(tok, model, adapter_name, rows, tag):
    """Fresh LoRA from the base on rows (list of (prompt, completion)).
    Manual loop (proven pattern, SPRA 2026-11-16): 2 epochs, batch 8."""
    import torch
    from peft import LoraConfig
    cfg = LoraConfig(r=LORA_R, lora_alpha=LORA_ALPHA, lora_dropout=0.0,
                     bias="none", task_type="CAUSAL_LM",
                     target_modules=TARGET_MODULES)
    model.add_adapter(adapter_name, cfg)
    model.set_adapter(adapter_name)
    n_train = sum(p.numel() for n, p in model.named_parameters()
                  if p.requires_grad)
    log(f"{tag}: adapter {adapter_name} active, {n_train/1e6:.1f}M trainable")
    opt = torch.optim.AdamW((p for p in model.parameters() if p.requires_grad),
                            lr=LORA_LR)
    enc_rows = [encode_train_example(tok, p, c) for p, c in rows]
    rng = random.Random(SEED + 3)
    steps = 0
    micro = 0
    t0 = time.time()
    for ep in range(EPOCHS):
        order = list(range(len(enc_rows)))
        rng.shuffle(order)
        for bi in range(0, len(order), TRAIN_BS):
            idx = order[bi:bi + TRAIN_BS]
            batch = [enc_rows[j] for j in idx]
            maxlen = max(len(ids) for ids, _ in batch)
            pad = tok.pad_token_id
            input_ids, labels, attn = [], [], []
            for ids, lab in batch:
                n_pad = maxlen - len(ids)
                input_ids.append(ids + [pad] * n_pad)
                labels.append(lab + [-100] * n_pad)
                attn.append([1] * len(ids) + [0] * n_pad)
            input_ids = torch.tensor(input_ids, device="cuda")
            labels = torch.tensor(labels, device="cuda")
            attn = torch.tensor(attn, device="cuda")
            out = model(input_ids=input_ids, attention_mask=attn, labels=labels)
            (out.loss / GRAD_ACCUM).backward()
            micro += 1
            if micro % GRAD_ACCUM == 0:
                torch.nn.utils.clip_grad_norm_(
                    [p for p in model.parameters() if p.requires_grad], 1.0)
                opt.step()
                opt.zero_grad(set_to_none=True)
                steps += 1
                if steps % 10 == 0:
                    log(f"  {tag} step {steps} loss {out.loss.item():.4f} "
                        f"elapsed {time.time()-t0:.0f}s "
                        f"VRAM {torch.cuda.memory_allocated()/2**30:.2f} GiB")
    if micro % GRAD_ACCUM != 0:  # flush a trailing partial accumulation
        torch.nn.utils.clip_grad_norm_(
            [p for p in model.parameters() if p.requires_grad], 1.0)
        opt.step()
        opt.zero_grad(set_to_none=True)
        steps += 1
    log(f"{tag} done: {steps} steps, {time.time()-t0:.0f}s, "
        f"peak VRAM {torch.cuda.max_memory_allocated()/2**30:.2f} GiB")
    os.makedirs(ADAPTER_DIR, exist_ok=True)
    model.save_pretrained(os.path.join(ADAPTER_DIR, adapter_name))
    log(f"saved adapter {adapter_name}")
    return steps


def eval_exam(tok, model, exam, adapter, tag, pool_programs):
    """Greedy eval on the fresh exam under the paper's protocol.
    adapter None = base. Returns (correct, n_graded, n_excluded, rows)."""
    import torch
    if adapter is None:
        model.disable_adapter()
    else:
        model.set_adapter(adapter)
    prompts = [eval_prompt(it["program"]) for it in exam]
    replies = batch_generate(tok, model, prompts, do_sample=False,
                             max_new_tokens=EVAL_MAX_NEW)
    pool_norm = {norm_program(p) for p in pool_programs}
    correct, n_graded, n_excl, rows = 0, 0, 0, []
    for it, rep in zip(exam, replies):
        if norm_program(it["program"]) in pool_norm:
            n_excl += 1
            rows.append({"item": it["id"], "template": it["template"],
                         "model": tag, "correct": "", "excluded": 1})
            continue
        ok = grade_answer(rep, it["reference"])
        n_graded += 1
        correct += int(ok)
        rows.append({"item": it["id"], "template": it["template"],
                     "model": tag, "correct": int(ok), "excluded": 0})
    exists = os.path.exists(EVAL_ROWS_CSV)
    with open(EVAL_ROWS_CSV, "a", newline="") as f:
        w = csv.DictWriter(f, fieldnames=["item", "template", "model",
                                          "correct", "excluded"])
        if not exists:
            w.writeheader()
        w.writerows(rows)
    log(f"{tag} exam: {correct}/{n_graded} graded "
        f"({n_excl} excluded as overlap with training pool)")
    return correct, n_graded, n_excl, rows


def sign_test_p(wins, losses):
    """Exact one-sided binomial p (wins > losses) over discordant items."""
    n = wins + losses
    if n == 0:
        return 1.0
    p = sum(math.comb(n, k) for k in range(wins, n + 1)) / 2 ** n
    return p


def propose_and_select(tok, model, champion, target, budget, sections,
                       seen_programs, tag):
    """Champion proposes programs; 4 temp-1.0 predictions each; frontier =
    >=1 wrong. Returns (frontier_rows, n_proposed, n_valid, n_frontier)."""
    import torch
    if champion is None:
        model.disable_adapter()
    else:
        model.set_adapter(champion)
    frontier, n_proposed, n_valid = [], 0, 0
    sec_i = 0
    while len(frontier) < target and n_proposed < budget:
        batch_n = min(40, budget - n_proposed)
        prompts, secs = [], []
        for _ in range(batch_n):
            sec = sections[sec_i % len(sections)]
            sec_i += 1
            prompts.append(
                f"Write a short Lua 5.1 program about {sec}. "
                "The program must use print() exactly once to print a "
                "single value. Reply with only the program in a fenced "
                "lua code block and nothing else.")
            secs.append(sec)
        replies = batch_generate(tok, model, prompts, do_sample=True,
                                 temperature=1.0,
                                 max_new_tokens=PROPOSE_MAX_NEW)
        candidates = []
        for rep in replies:
            n_proposed += 1
            code = extract_program(rep)
            if not code or len(code) > 800:
                continue
            if any(b in code for b in BANNED_SUBSTRINGS):
                continue
            if code.count("print(") != 1:
                continue
            if norm_program(code) in seen_programs:
                continue
            ref = run_lua(code)
            if ref is None or ref.strip() == "":
                continue
            seen_programs.add(norm_program(code))
            n_valid += 1
            candidates.append((code, ref))
        if not candidates:
            continue
        # 4 predictions each (temp 1.0), batched as repeated prompts.
        pred_prompts = []
        for code, _ in candidates:
            pred_prompts.extend([eval_prompt(code)] * PREDICT_SAMPLES)
        preds = batch_generate(tok, model, pred_prompts, do_sample=True,
                               temperature=1.0, max_new_tokens=PREDICT_MAX_NEW)
        for ci, (code, ref) in enumerate(candidates):
            outs = preds[ci * PREDICT_SAMPLES:(ci + 1) * PREDICT_SAMPLES]
            n_wrong = sum(0 if grade_answer(o, ref) else 1 for o in outs)
            if n_wrong >= 1:
                frontier.append({"program": code, "reference": ref,
                                 "n_wrong_of_4": n_wrong})
                if len(frontier) >= target:
                    break
        log(f"  {tag}: proposed {n_proposed}, valid {n_valid}, "
            f"frontier {len(frontier)}/{target}")
    return frontier, n_proposed, n_valid, len(frontier)


