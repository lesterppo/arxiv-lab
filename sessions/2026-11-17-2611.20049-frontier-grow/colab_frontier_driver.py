def setup_lua():
    """Pin Lua 5.1.5 semantics via the lua5.1 binary; BLOCKED if absent.

    Tiers: (1) lua5.1 / lua already on PATH; (2) apt install lua5.1
    (Ubuntu's is 5.1.5); (3) build 5.1.5 from source (pins the exact
    interpreter the paper used). Probes catch FileNotFoundError: a
    missing binary raises instead of returning non-zero (this killed
    the first launch of this run -- fixed 2026-11-17).
    """
    for cmd in (["lua5.1", "-v"], ["lua", "-v"]):
        try:
            r = subprocess.run(cmd, capture_output=True, text=True)
        except FileNotFoundError:
            continue
        if r.returncode == 0:
            log(f"lua available: {(r.stdout or r.stderr).strip()}")
            return cmd[0]
    log("lua5.1 not found; apt-get install")
    subprocess.run(["apt-get", "update", "-qq"], check=False)
    r = subprocess.run(["apt-get", "install", "-y", "-qq", "lua5.1"],
                       capture_output=True, text=True)
    if r.returncode == 0:
        try:
            r = subprocess.run(["lua5.1", "-v"], capture_output=True, text=True)
        except FileNotFoundError:
            r = None
        if r is not None and r.returncode == 0:
            log(f"lua available: {(r.stdout or r.stderr).strip()}")
            return "lua5.1"
    log("apt lua5.1 failed; building Lua 5.1.5 from source")
    build_dir = "/tmp/lua515"
    subprocess.run(["rm", "-rf", build_dir], check=False)
    os.makedirs(build_dir, exist_ok=True)
    url = "https://www.lua.org/ftp/lua-5.1.5.tar.gz"
    steps = [
        ["curl", "-fsSL", "-o", f"{build_dir}/lua.tar.gz", url],
        ["tar", "xzf", f"{build_dir}/lua.tar.gz", "-C", build_dir,
         "--strip-components=1"],
        ["make", "-C", build_dir, "linux", "-j4"],
    ]
    for s in steps:
        r = subprocess.run(s, capture_output=True, text=True)
        if r.returncode != 0:
            log(f"lua source build step failed: {' '.join(s)}")
            return None
    lua_bin = os.path.join(build_dir, "src", "lua")
    try:
        r = subprocess.run([lua_bin, "-v"], capture_output=True, text=True)
    except FileNotFoundError:
        return None
    if r.returncode == 0:
        log(f"lua available: {(r.stdout or r.stderr).strip()} (built from source)")
        return lua_bin
    return None


LUA_BIN = None


def run_lua(code, timeout=2.0):
    """Run code with the interpreter; return output string or None.

    Reference = output run twice, must be equal (paper's rule).
    """
    outs = []
    for _ in range(2):
        try:
            r = subprocess.run([LUA_BIN, "-e", code], capture_output=True,
                               text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            return None
        if r.returncode != 0:
            return None
        outs.append(r.stdout)
    if outs[0] != outs[1]:
        return None
    return outs[0]


def norm_program(code):
    """Normalize for overlap exclusion: strip comments + whitespace."""
    code = re.sub(r"--\[\[.*?\]\]", "", code, flags=re.S)
    code = re.sub(r"--[^\n]*", "", code)
    return re.sub(r"\s+", "", code)


def grade_answer(reply, reference):
    """Paper's grading: last fenced block (or whole reply), compared
    token by token per line, whitespace runs collapsed, blank lines
    ignored."""
    blocks = re.findall(r"```(?:\w*\n)?(.*?)```", reply, flags=re.S)
    ans = blocks[-1] if blocks else reply

    def norm(s):
        lines = []
        for ln in s.splitlines():
            ln = re.sub(r"\s+", " ", ln).strip()
            if ln:
                lines.append(ln)
        return lines
    return norm(ans) == norm(reference)


def extract_program(reply):
    """First fenced block (lua or plain) of a proposal reply."""
    blocks = re.findall(r"```(?:lua\n|Lua\n|\n)?(.*?)```", reply, flags=re.S)
    if blocks:
        return blocks[0].strip()
    return reply.strip()


