def load_data():
    from datasets import load_dataset
    log("loading Banking77 (PolyAI/banking77)")
    ds = load_dataset("PolyAI/banking77")
    label_names = ds["train"].features["label"].names
    assert len(label_names) == 77, f"expected 77 labels, got {len(label_names)}"
    label_set = set(label_names)
    log(f"banking77: train {len(ds['train'])} test {len(ds['test'])} labels 77")

    train_pool = ds["train"].shuffle(seed=SEED)
    trace_items = [{"text": train_pool[i]["text"],
                    "gold": label_names[train_pool[i]["label"]]}
                   for i in range(TRACE_POOL)]
    train_texts = {it["text"] for it in trace_items}

    test_pool = ds["test"].shuffle(seed=SEED)
    test_rows, j, overlap = [], 0, 0
    while len(test_rows) < EVAL_N and j < len(test_pool):
        r = test_pool[j]; j += 1
        if r["text"] in train_texts:
            overlap += 1
            continue
        test_rows.append({"text": r["text"], "gold": label_names[r["label"]]})
    assert len(test_rows) == EVAL_N, f"only {len(test_rows)} disjoint test rows"
    log(f"sets: trace_pool {len(trace_items)} banking77_test {len(test_rows)} "
        f"overlap_dropped {overlap}")

    log("downloading MMLU validation parquet (cais/mmlu, all)")
    urllib.request.urlretrieve(
        "https://huggingface.co/datasets/cais/mmlu/resolve/main/all/validation-00000-of-00001.parquet",
        "/tmp/mmlu_val.parquet")
    mmlu = pd.read_parquet("/tmp/mmlu_val.parquet")
    assert {"question", "choices", "answer"}.issubset(mmlu.columns), mmlu.columns
    step = max(1, len(mmlu) // MMLU_N)
    idxs = strided_indices(len(mmlu), MMLU_N)
    mmlu_rows = [{"question": r["question"], "choices": list(r["choices"]),
                  "answer": int(r["answer"])}
                 for _, r in mmlu.iloc[idxs].iterrows()][:MMLU_N]
    log(f"mmlu: {len(mmlu)} rows, strided subset {len(mmlu_rows)} (step {step})")
    return label_names, label_set, trace_items, test_rows, mmlu_rows


def build_arms(traced_items):
    """Matched arms on the SAME items: R = label only, T = trace + label.

    `traced_items` is a list of {prompt, gold, reasoning}. Raises if the
    pool is too small to train on. Returns (arm_r, arm_t, n)."""
    n = min(N_TARGET, len(traced_items))
    if n < MIN_ARMS:
        raise RuntimeError(
            f"traced pool short: have {len(traced_items)}, need >= {MIN_ARMS}")
    items = traced_items[:n]
    arm_r = [{"prompt": it["prompt"], "completion": f" {it['gold']}",
              "gold": it["gold"]} for it in items]
    arm_t = [{"prompt": it["prompt"],
              "completion": f" {it['reasoning']}\nCategory: {it['gold']}",
              "gold": it["gold"]} for it in items]
    assert len(arm_r) == len(arm_t) == n
    assert all(a["prompt"] == b["prompt"] for a, b in zip(arm_r, arm_t))
    return arm_r, arm_t, n


