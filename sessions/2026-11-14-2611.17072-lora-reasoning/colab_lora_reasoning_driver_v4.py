def build_model():
    import torch
    from transformers import AutoModelForCausalLM, AutoTokenizer, BitsAndBytesConfig
    from peft import LoraConfig, get_peft_model
    log("loading tokenizer + base model (NF4)")
    tok = AutoTokenizer.from_pretrained(MODEL_ID)
    if tok.pad_token is None:
        tok.pad_token = tok.eos_token
    tok.padding_side = "right"
    bnb = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type="nf4",
                             bnb_4bit_use_double_quant=True,
                             bnb_4bit_compute_dtype=torch.bfloat16)
    model = AutoModelForCausalLM.from_pretrained(
        MODEL_ID, quantization_config=bnb, device_map="auto",
        torch_dtype=torch.bfloat16)
    model.config.use_cache = False
    cfg = LoraConfig(r=16, lora_alpha=32, lora_dropout=0.0, bias="none",
                     task_type="CAUSAL_LM",
                     target_modules=["q_proj", "k_proj", "v_proj", "o_proj",
                                     "gate_proj", "up_proj", "down_proj"])
    model = get_peft_model(model, cfg)
    model.print_trainable_parameters()
    log(f"VRAM after load: {torch.cuda.memory_allocated()/2**30:.2f} GiB allocated, "
        f"{torch.cuda.max_memory_allocated()/2**30:.2f} GiB peak")
    return tok, model


# ---------------------------------------------------------------- train/eval helpers
def make_batches(items, bs):
    for i in range(0, len(items), bs):
        yield items[i:i + bs]


def train_sft(tok, model, examples, lr, epochs, tag):
    """Plain SFT loop, HF built-in loss (proven soup recipe), micro-batch 2."""
    import torch
    from torch.utils.data import DataLoader, Dataset
    from transformers import get_cosine_schedule_with_warmup

    class SFTData(Dataset):
        def __init__(self, exs):
            self.rows = []
            for e in exs:
                p = tok(e["prompt"], add_special_tokens=False)["input_ids"]
                c = tok(e["completion"], add_special_tokens=False)["input_ids"] + [tok.eos_token_id]
                ids = (p + c)[:512]
                labels = ([-100] * len(p) + c)[:512]
                self.rows.append((ids, labels))

        def __len__(self):
            return len(self.rows)

        def __getitem__(self, i):
            return self.rows[i]

    def collate(batch):
        mx = max(len(ids) for ids, _ in batch)
        pad = tok.pad_token_id
        input_ids, labels, attn = [], [], []
        for ids, lab in batch:
            n = mx - len(ids)
            input_ids.append(ids + [pad] * n)
            labels.append(lab + [-100] * n)
            attn.append([1] * len(ids) + [0] * n)
        return (torch.tensor(input_ids), torch.tensor(labels),
                torch.tensor(attn))

    # OOM fix (2026-11-12 run e): without gradient checkpointing, bnb's
    # dequantized bf16 weights are retained for backward across all layers.
    torch.cuda.empty_cache()
    model.gradient_checkpointing_enable()
    try:
        model.enable_input_require_grads()
    except Exception:
        pass
    model.train()
    model.config.use_cache = False
    GRAD_ACCUM = 2  # micro-batch 2 x accum 2 = effective batch 4
    dl = DataLoader(SFTData(examples), batch_size=2, shuffle=True, collate_fn=collate)
    opt = torch.optim.AdamW((p for p in model.parameters() if p.requires_grad),
                            lr=lr, weight_decay=0.0)
    total = (len(dl) * epochs + GRAD_ACCUM - 1) // GRAD_ACCUM
    sched = get_cosine_schedule_with_warmup(opt, 3, total)
    step = 0
    t0 = time.time()
    opt.zero_grad(set_to_none=True)
    for ep in range(epochs):
        for mbi, (input_ids, labels, attn) in enumerate(dl):
            input_ids, labels, attn = (input_ids.cuda(), labels.cuda(), attn.cuda())
            with torch.autocast("cuda", dtype=torch.bfloat16):
                out = model(input_ids=input_ids, attention_mask=attn, labels=labels)
            (out.loss / GRAD_ACCUM).backward()
            if (mbi + 1) % GRAD_ACCUM == 0 or mbi == len(dl) - 1:
                torch.nn.utils.clip_grad_norm_(
                    (p for p in model.parameters() if p.requires_grad), 1.0)
                opt.step()
                sched.step()
                opt.zero_grad(set_to_none=True)
                step += 1
                if step % 25 == 0 or step == total:
                    log(f"{tag} step {step}/{total} loss {out.loss.item():.4f} "
                        f"elapsed {time.time()-t0:.0f}s "
                        f"VRAM {torch.cuda.memory_allocated()/2**30:.2f} GiB")
    log(f"{tag} done: {step} steps, {time.time()-t0:.0f}s, "
        f"peak VRAM {torch.cuda.max_memory_allocated()/2**30:.2f} GiB")
    return step


def run_eval_banking(tok, model, items, label_names, bs=8, tag="eval"):
    """Greedy Banking77 eval; returns dict with acc, parse-fail, macro-F1,
    ECE (first-generated-token confidence, 5 bins)."""
    import torch
    model.eval()
    model.config.use_cache = True
    tok.padding_side = "left"
    preds, golds, confs, corrects = [], [], [], []
    for batch in make_batches(items, bs):
        prompts = [b["prompt"] for b in batch]
        enc = tok(prompts, return_tensors="pt", padding=True, add_special_tokens=False)
        enc = {k: v.cuda() for k, v in enc.items()}
        plen = enc["input_ids"].shape[1]
        with torch.no_grad():
            out = model.generate(**enc, max_new_tokens=EVAL_MAX_NEW, do_sample=False,
                                 pad_token_id=tok.eos_token_id,
                                 output_scores=True, return_dict_in_generate=True)
        first_scores = torch.log_softmax(out.scores[0].float(), dim=-1)
        for i, b in enumerate(batch):
            gen = tok.decode(out.sequences[i][plen:], skip_special_tokens=True)
            pred = parse_pred(gen, label_names)
            first_tok = int(out.sequences[i][plen])
            conf = float(torch.exp(first_scores[i][first_tok]))
            preds.append(pred)
            golds.append(b["gold"])
            confs.append(conf)
            corrects.append(1 if pred == b["gold"] else 0)
        torch.cuda.empty_cache()
    tok.padding_side = "right"
    n = len(items)
    correct = sum(corrects)
    pf = sum(1 for p in preds if p is None) / n
    f1 = macro_f1(preds, golds, label_names)
    ece = compute_ece(confs, corrects)
    log(f"{tag}: acc {correct}/{n}={correct/n:.4f} parse_fail {pf:.4f} "
        f"macro_f1 {f1:.4f} ece {ece:.4f}")
    return {"n": n, "correct": correct, "acc": correct / n,
            "parse_fail": pf, "macro_f1": f1, "ece": ece}


def run_eval_mmlu(tok, model, items, bs=16, tag="mmlu"):
    """Logprob-scored MMLU: pick argmax over ' A'/' B'/' C'/' D' continuations."""
    import torch
    model.eval()
    model.config.use_cache = True
    tok.padding_side = "left"
    letters = [" A", " B", " C", " D"]
    letter_ids = []
    for L in letters:
        ids = tok(L, add_special_tokens=False)["input_ids"]
        assert len(ids) == 1, f"{L!r} is not a single token: {ids}"
        letter_ids.append(ids[0])
    correct = 0
    for batch in make_batches(items, bs):
        prompts = []
        for b in batch:
            opts = "\n".join(f"{chr(65 + k)}. {c}" for k, c in enumerate(b["choices"]))
            prompts.append(f"Question: {b['question']}\n{opts}\nAnswer:")
        enc = tok(prompts, return_tensors="pt", padding=True, add_special_tokens=False)
        enc = {k: v.cuda() for k, v in enc.items()}
        with torch.no_grad():
            logits = model(**enc).logits[:, -1, :].float()
        logp = torch.log_softmax(logits, dim=-1)
        for i, b in enumerate(batch):
            pred = max(range(4), key=lambda k: float(logp[i][letter_ids[k]]))
            correct += 1 if pred == b["answer"] else 0
        torch.cuda.empty_cache()
    tok.padding_side = "right"
    log(f"{tag}: {correct}/{len(items)} = {correct/len(items):.4f}")
    return {"n": len(items), "correct": correct, "acc": correct / len(items)}


def load_traced_from_jsonl(path):
    """Load traced items persisted by an earlier run's Phase GEN
    (rows: text, gold, reasoning, prompt). Used when
    LORA_REUSE_TRACES=1 so a re-run skips the ~1h generation phase."""
    rows = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            r = json.loads(line)
            assert {"text", "gold", "reasoning", "prompt"} <= set(r), sorted(r)
            rows.append({"text": r["text"], "gold": r["gold"],
                         "reasoning": r["reasoning"], "prompt": r["prompt"]})
    return rows


def run_trace_gen(tok, model, items, label_names, bs=8, tag="tracegen"):
    """Greedy few-shot trace generation; persists kept traces to JSONL as
    they are produced (reclamation-safe). Returns list of traced items."""
    import torch
    model.eval()
    model.config.use_cache = True
    tok.padding_side = "left"
    traced, attempted = [], 0
    if os.path.exists(TRACES_JSONL):
        os.remove(TRACES_JSONL)
    for batch in make_batches(items, bs):
        prompts = [make_trace_prompt(b["text"], label_names) for b in batch]
        enc = tok(prompts, return_tensors="pt", padding=True, add_special_tokens=False)
        enc = {k: v.cuda() for k, v in enc.items()}
        plen = enc["input_ids"].shape[1]
        with torch.no_grad():
            out = model.generate(**enc, max_new_tokens=TRACE_MAX_NEW,
                                 do_sample=False,
                                 pad_token_id=tok.eos_token_id)
        for i, b in enumerate(batch):
            attempted += 1
            gen = tok.decode(out[i][plen:], skip_special_tokens=True)
            reasoning = extract_trace(gen, label_names, b["gold"])
            if reasoning is not None:
                row = {"text": b["text"], "gold": b["gold"],
                       "reasoning": reasoning,
                       "prompt": make_prompt(b["text"], label_names)}
                traced.append(row)
                with open(TRACES_JSONL, "a") as f:
                    f.write(json.dumps(row) + "\n")
        if attempted % 80 == 0:
            log(f"{tag}: {attempted}/{len(items)} attempted, {len(traced)} kept")
        torch.cuda.empty_cache()
    tok.padding_side = "right"
    log(f"{tag}: kept {len(traced)}/{attempted} "
        f"({len(traced)/max(1, attempted):.3f} yield)")
    return traced


