def normalize_label(s):
    """'Card Arrival' / 'card-arrival' -> 'card_arrival'."""
    if s is None:
        return None
    return re.sub(r"[\s\-]+", "_", s.strip().lower()).strip("_.,;: ")


def make_prompt(text, label_names):
    label_list = "\n".join(f"- {n}" for n in label_names)
    return (
        "Classify the following banking support message into exactly one category.\n\n"
        f"Categories:\n{label_list}\n\n"
        f"Message: {text}\n"
        "Category:"
    )


# Two hand-written few-shot exemplars for trace generation (own wording,
# Banking77-style messages; labels are real Banking77 labels).
TRACE_EXAMPLES = [
    ("I lost my wallet and my card was inside it. Can you block the card?",
     "The user reports a lost card and asks for it to be blocked.",
     "lost_or_stolen_card"),
    ("When will my replacement card arrive? I ordered it last week.",
     "The user asks about the delivery time of a card they already ordered.",
     "card_arrival"),
]


def make_trace_prompt(text, label_names, examples=TRACE_EXAMPLES):
    label_list = "\n".join(f"- {n}" for n in label_names)
    parts = [
        "Classify banking support messages into exactly one category from this list.\n\n"
        f"Categories:\n{label_list}\n"
    ]
    for msg, reasoning, label in examples:
        parts.append(f"\nMessage: {msg}\nReasoning: {reasoning}\nCategory: {label}\n")
    parts.append(f"\nMessage: {text}\nReasoning:")
    return "".join(parts)


TRACE_CAT_RE = re.compile(r"Category:\s*(.+)", re.IGNORECASE)


def parse_pred(raw, label_names):
    """Normalise a raw generation to a label name, or None (parse fail).

    Priority (v3 fix): (1) first line, if it is a label (response-only /
    base generations); (2) a "Category: <label>" line anywhere (the
    reasoning arm's generations end with one); (3) any label name in
    the full text. v2 only looked at the first line, so reasoning-arm
    generations -- reasoning text first, label on a later line -- all
    parse-failed under the 16-token cap."""
    if raw is None:
        return None
    first = raw.strip().splitlines()[0] if raw.strip() else ""
    norm_first = normalize_label(first.strip().strip('"').strip("'").strip())
    if norm_first in label_names:
        return norm_first
    m = TRACE_CAT_RE.search(raw)
    if m and normalize_label(m.group(1)) in label_names:
        return normalize_label(m.group(1))
    norm_full = normalize_label(raw)
    for name in label_names:
        if name in norm_full:
            return name
    return None


def extract_trace(raw, label_names, gold):
    """Validate a generated trace: must end with 'Category: <gold label>'.

    Returns the cleaned reasoning text (without the Category line), or
    None when the trace is unusable (no Category line, wrong label,
    empty reasoning)."""
    if raw is None:
        return None
    m = TRACE_CAT_RE.search(raw)
    if not m:
        return None
    if normalize_label(m.group(1)) != gold:
        return None
    reasoning = raw[:m.start()].strip()
    reasoning = re.sub(r"\s+", " ", reasoning)
    if len(reasoning) < 10 or len(reasoning) > 400:
        return None
    return reasoning


def compute_ece(confidences, corrects, n_bins=5):
    """Expected calibration error over equal-width confidence bins."""
    if not confidences:
        return 0.0
    total = 0.0
    n = len(confidences)
    for b in range(n_bins):
        lo, hi = b / n_bins, (b + 1) / n_bins
        idx = [i for i, c in enumerate(confidences) if lo <= c < hi or (b == n_bins - 1 and c == 1.0)]
        if not idx:
            continue
        bin_conf = sum(confidences[i] for i in idx) / len(idx)
        bin_acc = sum(corrects[i] for i in idx) / len(idx)
        total += (len(idx) / n) * abs(bin_acc - bin_conf)
    return total


def macro_f1(preds, golds, label_names):
    per = {}
    for p, g in zip(preds, golds):
        tp, fp, fn = per.get(g, [0, 0, 0])
        if p == g:
            tp += 1
        else:
            if p is not None:
                a, b_, c_ = per.get(p, [0, 0, 0])
                per[p] = [a, b_ + 1, c_]
            fn += 1
        per[g] = [tp, fp, fn]
    f1s = []
    for tp, fp, fn in per.values():
        prec = tp / max(1, tp + fp)
        rec = tp / max(1, tp + fn)
        f1s.append(2 * prec * rec / max(1e-9, prec + rec))
    return float(sum(f1s) / len(f1s)) if f1s else 0.0


def strided_indices(total, want):
    """Evenly strided indices covering a list of length `total` with at
    most `want` items (used for the MMLU retention subset)."""
    if total <= want:
        return list(range(total))
    step = max(1, total // want)
    return list(range(0, total, step))[:want]


